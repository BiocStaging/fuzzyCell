## the packaged lung subset is ready for the analyses with its tree
test_that("lungSubset has the columns, images and cell types the analyses need", {
    data(lungSubset)
    data(lungCellTypeTree)
    expect_s4_class(lungSubset, "SpatialExperiment")
    cd = SummarizedExperiment::colData(lungSubset)
    expect_true(all(c("cellID", "imageID", "subject", "cellType", "disease_status") %in% names(cd)))
    expect_false(anyDuplicated(cd$cellID) > 0)
    expect_equal(colnames(lungSubset), cd$cellID)
    expect_setequal(unique(cd$disease_status), c("Control", "Disease"))
    images = unique(as.data.frame(cd)[, c("imageID", "subject", "disease_status")])
    expect_equal(nrow(images), 10)
    expect_false(anyDuplicated(images$subject) > 0)
    expect_equal(as.vector(table(images$disease_status)), c(5, 5))
    expect_true(all(cd$cellType %in% buildCellTypeMap(lungCellTypeTree)$cellMap$cellType))
    expect_true(all(table(cd$cellType) >= 20))
    counts = SummarizedExperiment::assay(lungSubset, "counts")
    expect_true(all(counts@x == round(counts@x)))
})
